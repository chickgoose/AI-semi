class QualificationError(ValueError):
    pass


def _regular(path: Path) -> bytes:
    try:
        info = path.lstat()
    except FileNotFoundError as exc:
        raise QualificationError(f"missing artifact: {path}") from exc
    if not stat.S_ISREG(info.st_mode) or path.is_symlink():
        raise QualificationError(f"artifact is not a regular non-symlink file: {path}")
    data = path.read_bytes()
    if not data:
        raise QualificationError(f"artifact is empty: {path}")
    return data


def _text(path: Path) -> str:
    try:
        return _regular(path).decode("utf-8")
    except UnicodeDecodeError as exc:
        raise QualificationError(f"artifact is not UTF-8: {path}") from exc


def _require_clean_log(path: Path) -> str:
    text = _text(path)
    versions = VERSION_LINE.findall(text)
    if versions != [INNOVUS_VERSION]:
        raise QualificationError(
            f"Innovus log version is not exactly {INNOVUS_VERSION}: {path}"
        )
    if BAD_LOG.search(text):
        raise QualificationError(f"Innovus log contains an error/interruption marker: {path}")
    summaries = [int(value) for value in MESSAGE_SUMMARY.findall(text)]
    if not summaries or any(value != 0 for value in summaries):
        raise QualificationError(f"Innovus log lacks an all-zero error summary: {path}")
    if not INNOVUS_END.search(text):
        raise QualificationError(f"Innovus log lacks the normal ending record: {path}")
    return text


def _require_nonempty_directory(path: Path) -> None:
    try:
        info = path.lstat()
    except FileNotFoundError as exc:
        raise QualificationError(f"missing artifact directory: {path}") from exc
    if not stat.S_ISDIR(info.st_mode) or path.is_symlink():
        raise QualificationError(f"artifact directory is invalid: {path}")
    if not any(path.iterdir()):
        raise QualificationError(f"artifact directory is empty: {path}")


def _timing_profile_contract(profile_id: str) -> dict[str, str]:
    registry = json.loads(
        (HERE / "k2_physical_innovus_cohorts.json").read_text(encoding="utf-8"))
    profile = registry.get("timing_profiles", {}).get(profile_id)
    if not isinstance(profile, dict):
        raise QualificationError("execution descriptor timing profile is unknown")
    digest = hashlib.sha256((json.dumps(
        {"id": profile_id, "profile": profile}, indent=2, sort_keys=True
    ) + "\n").encode()).hexdigest()
    hold = profile.get("hold_fix_allow_setup_tns_degrade")
    if hold is not (profile_id in {
            "three_endpoint_5p7ns", "three_endpoint_6p5ns"}):
        raise QualificationError("hold setup-degrade policy does not match profile")
    pointer = registry.get("timing_cohort_manifest", {})
    timing_path = HERE.parents[1] / str(pointer.get("path", ""))
    try:
        timing_payload = timing_path.read_bytes()
        timing_manifest = json.loads(timing_payload)
    except (OSError, json.JSONDecodeError) as error:
        raise QualificationError("Genus timing manifest is unreadable") from error
    manifest_sha = hashlib.sha256(timing_payload).hexdigest()
    genus_profile = timing_manifest.get("cohorts", {}).get(profile_id)
    if (pointer.get("required_schema") != "k2_w2_genus_timing_cohorts_v1" or
            pointer.get("sha256") != manifest_sha or
            timing_manifest.get("schema") != pointer["required_schema"] or
            not isinstance(genus_profile, dict)):
        raise QualificationError("Genus timing manifest/profile mismatch")
    genus_profile_sha = hashlib.sha256((json.dumps(
        {"id": profile_id, "profile": genus_profile}, indent=2, sort_keys=True
    ) + "\n").encode()).hexdigest()
    return {
        "id": profile_id,
        "profile_sha256": digest,
        "genus_timing_manifest_sha256": manifest_sha,
        "genus_timing_profile_sha256": genus_profile_sha,
        "period_ns": profile["period_ns"],
        "hold_fix_allow_setup_tns_degrade": str(hold).lower(),
    }


