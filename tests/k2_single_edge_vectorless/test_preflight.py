def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(flow.canonical(value))


def contract_and_sources() -> tuple[dict, dict]:
    contract, _ = flow.load_contract(ROOT)
    return contract, flow.validate_contract(ROOT, contract)


