def structural_netlist(top: str) -> bytes:
    inputs = "\n".join((
        "input clk_i;", "input rst_i;", "input link_enable_i;",
        "input [15:0] source_pending_i;",
    ))
    outputs = "\n".join((
        "output [15:0] source_accept_o;", "output [1:0] accept_count_o;",
        "output [3:0] accept_addr0_o;", "output [3:0] accept_addr1_o;",
        "output link_valid_o;", "output [3:0] link_addr0_o;",
        "output [3:0] link_addr1_o;", "output [1:0] retire_valid_o;",
        "output [3:0] retire_addr0_o;", "output [3:0] retire_addr1_o;",
        "output protocol_error_o;", "output drain_idle_o;",
    ))
    return f"""module {top} (clk_i, rst_i, link_enable_i, source_pending_i,
source_accept_o, accept_count_o, accept_addr0_o, accept_addr1_o, link_valid_o,
link_addr0_o, link_addr1_o, retire_valid_o, retire_addr0_o, retire_addr1_o,
protocol_error_o, drain_idle_o);
{inputs}
{outputs}
DFFX1 state_q (.D(link_enable_i), .CK(clk_i), .Q(link_valid_o));
endmodule
""".encode()


def diagnostic_index(root: Path, contract: dict, contract_payload: bytes) -> Path:
    for name in ("a2", "a3"):
        (root / name).mkdir()
    order = contract["decision_policy"]["candidate_order"]
    document = {
        "schema": "k2_single_edge_vectorless_diagnostic_index_v2",
        "evidence_class": contract["evidence_class"],
        "candidate_order": order,
        "interface": "SINGLE_EDGE_PARALLEL",
        "contract_sha256": flow.sha256(contract_payload),
        "rows": [
            {"candidate": candidate, "top": contract["candidates"][candidate]["top"],
             "attempt_directory": "a2" if index == 0 else "a3"}
            for index, candidate in enumerate(order)
        ],
    }
    path = root / "diagnostic-index.json"
    write_json(path, document)
    return path


def fake_diagnostic_rows(contract: dict) -> list[dict]:
    rows = []
    for index, candidate in enumerate(contract["decision_policy"]["candidate_order"]):
        rows.append({
            "candidate": candidate, "top": contract["candidates"][candidate]["top"],
            "receipt": {"fabricated": True}, "receipt_sha256": str(index + 1) * 64,
            "power": {"total_mw": 1.0}, "capture_id": f"fabricated-{index}",
            "claimed_host_fingerprint_sha256": "a" * 64,
            "artifact_ledger_sha256": "b" * 64,
            "structural_diagnostic": {"structural_instance_count": 1},
        })
    return rows


class ContractTest(unittest.TestCase):
    def test_hardened_commits_exact_filelists_sources_and_error_latch(self) -> None:
        contract, sources = contract_and_sources()
        self.assertEqual(sources["equivalent_hardened_commits"], [
            "a0a4eb38632245db8ff5937ea5b6c6e3f3839246",
            "6fc5e167918fa4c54786c9a3abb5f60ecd8b991b",
        ])
        for candidate, row in sources["candidates"].items():
            self.assertEqual(len(row["filelists"]), 2, candidate)
            self.assertEqual(len(row["sources"]), 6, candidate)
            self.assertIn("rtl/technology/single_edge/w2_single_edge_error_latch.sv",
                          [source["path"] for source in row["sources"]])
        self.assertFalse(contract["decision_policy"]["candidate_go_possible"])
        self.assertFalse(contract["decision_policy"]["comparison_ready_possible"])

    def test_complete_boundary_port_sets_are_exact(self) -> None:
        contract, _ = contract_and_sources()
        for row in contract["candidates"].values():
            self.assertEqual(row["inputs"], flow.EXPECTED_INPUTS)
            self.assertEqual(row["outputs"], flow.EXPECTED_OUTPUTS)
        for mutate in ("drop", "add", "reorder"):
            changed = copy.deepcopy(contract)
            ports = changed["candidates"]["a2_single_edge"]["outputs"]
            if mutate == "drop":
                ports.pop()
            elif mutate == "add":
                ports.append("invented_o")
            else:
                ports.reverse()
            with self.subTest(mutate=mutate), self.assertRaises(flow.EvidenceError):
                flow.validate_contract(ROOT, changed)

    def test_placeholder_and_no_controlled_producer_are_immutable(self) -> None:
        contract, _ = contract_and_sources()
        expected = {
            "status": "UNCONFIRMED_TEAM_PLACEHOLDER",
            "evidence_class": "TEAM_PLACEHOLDER_SCREENING_ONLY",
            "external_authority_available": False,
            "values_are_release_claims": False,
            "candidate_go_eligible": False,
            "comparison_ready_eligible": False,
            "maximum_status": flow.HOLD_STATUS,
        }
        self.assertEqual(contract["constraint_authority"], expected)
        provenance = contract["diagnostic_provenance"]
        for field in ("controlled_runner_available", "live_host_binding_available",
                      "freshness_or_replay_protection_available",
                      "keyring_or_hmac_accepted", "structural_validation_implies_equivalence",
                      "structural_validation_implies_signoff"):
            self.assertIs(provenance[field], False, field)
        for field, value in (("candidate_go_eligible", True),
                             ("comparison_ready_eligible", True),
                             ("external_authority_available", True)):
            changed = copy.deepcopy(contract)
            changed["constraint_authority"][field] = value
            with self.subTest(field=field), self.assertRaises(flow.EvidenceError):
                flow.validate_contract(ROOT, changed)

    def test_driver_and_sdc_are_default_vectorless_placeholder_only(self) -> None:
        contract, _ = contract_and_sources()
        driver = (ROOT / contract["templates"]["driver"]["path"]).read_text()
        self.assertIn("K2_SE_ACTIVITY_MODE", driver)
        self.assertIn("GENUS_DEFAULT_VECTORLESS", driver)
        self.assertIn("check_design -all", driver)
        self.assertEqual(driver.count("report_power"), 1)
        for token in contract["activity_policy"]["forbidden_tokens"]:
            self.assertNotIn(token, driver.lower())
        sdc = (ROOT / contract["templates"]["sdc"]["path"]).read_text()
        self.assertIn("UNCONFIRMED_TEAM_PLACEHOLDER", sdc)
        self.assertEqual(sdc.count("create_clock "), 1)
        self.assertNotIn("create_generated_clock", sdc)

    def test_template_is_explicit_diagnostic_hold(self) -> None:
        template = json.loads((ROOT /
            "physical/k2_single_edge_vectorless/diagnostic-receipt.template.json").read_text())
        self.assertEqual(template["maximum_status"], flow.HOLD_STATUS)
        self.assertFalse(template["candidate_go"])
