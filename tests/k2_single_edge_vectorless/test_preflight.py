class PreflightTest(unittest.TestCase):
    def test_preflight_is_eda_free_honest_hold(self) -> None:
        real_run = subprocess.run
        calls: list[list[str]] = []

        def git_only(argv, *args, **kwargs):
            calls.append(list(argv))
            self.assertEqual(argv[0], "git")
            return real_run(argv, *args, **kwargs)

        with tempfile.TemporaryDirectory() as temporary, mock.patch.object(
                flow.subprocess, "run", side_effect=git_only):
            output = Path(temporary) / "preflight.json"
            flow.preflight(ROOT, output)
            result = json.loads(output.read_text())
        self.assertTrue(calls)
        self.assertEqual(result["status"],
                         "HOLD_NO_PRODUCER_BOUND_SERVER_ARTIFACTS")
        self.assertFalse(result["candidate_go"])
        self.assertFalse(result["comparison_ready"])
        self.assertFalse(result["activity_annotated"])
        self.assertEqual(result["power_method"],
                         "GENUS_MAPPED_DEFAULT_VECTORLESS")

    def test_preflight_output_is_create_exclusive(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "preflight.json"
            flow.preflight(ROOT, output)
            with self.assertRaisesRegex(flow.EvidenceError, "immutable output"):
                flow.preflight(ROOT, output)

    def test_cli_reports_hold_not_pass_or_go(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "preflight.json"
            completed = subprocess.run(
                ["python3", str(FLOW), "preflight", "--repo-root", str(ROOT),
                 "--output", str(output)], text=True, capture_output=True,
                check=False)
            self.assertEqual(completed.returncode, 0, completed.stderr)
            self.assertIn("K2_SINGLE_EDGE_VECTORLESS_HOLD", completed.stdout)
            self.assertNotIn("_GO", completed.stdout)
            self.assertNotIn("_PASS", completed.stdout)


