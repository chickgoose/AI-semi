class QualificationDecisionTest(unittest.TestCase):
    def test_attestation_mac_covers_complete_receipt_payload(self) -> None:
        secret = bytes(range(32))
        unsigned = {"schema": "test", "complete_artifact_ledger_sha256": "a" * 64}
        mac = hmac.new(secret, flow.canonical(unsigned), hashlib.sha256).hexdigest()
        receipt = {**unsigned, "attestation": {"key_id": "producer", "mac_sha256": mac}}
        row = {"candidate": "a2_single_edge", "receipt": receipt}
        flow._authenticate(row, {"producer": secret})
        receipt["complete_artifact_ledger_sha256"] = "b" * 64
        with self.assertRaisesRegex(flow.EvidenceError, "MAC mismatch"):
            flow._authenticate(row, {"producer": secret})

