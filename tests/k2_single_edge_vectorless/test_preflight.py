def power_report(top: str, *, activity: str = "N.A.", user: str = "N.A.",
                 sequential: str = "0.200000", primary: str = "0.200000") -> bytes:
    return f"""Generated by:           Genus(TM) Synthesis Solution
Instance: /{top}
* User-Defined Activity : {user}
* Activity File: {activity}
* Sequential Element Activity: {sequential}
* Primary Input Activity: {primary}
Power Unit: W
    Category         Leakage     Internal    Switching        Total
    Subtotal     1.00000e-09  1.00000e-06  1.00000e-06  2.00100e-06
""".encode()


def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(flow.canonical(value))


def contract_and_sources() -> tuple[dict, dict]:
    contract, _ = flow.load_contract(ROOT)
    sources = flow.validate_contract(ROOT, contract)
    return contract, sources


def receipt_shell(schema: str, contract: dict, candidate: str,
                  *, synthetic: bool = False, inherited: bool = False,
                  p6: bool = False) -> dict:
    design = contract["candidates"][candidate]
    return {
        "schema": schema,
        "status": "PRODUCER_COMPLETE",
        "evidence_class": contract["evidence_class"],
        "candidate": candidate,
        "architecture": design["architecture"],
        "interface": "SINGLE_EDGE_PARALLEL",
        "boundary": design["boundary"],
        "lineage": {"synthetic": synthetic, "inherited": inherited,
                    "p6": p6, "borrowed_dependency_ids": []},
        "top": design["top"],
        "producer": {},
        "operating_point": contract["operating_point"],
        "activity_policy": contract["activity_policy"],
        "tool": contract["tool"],
        "execution": {},
        "artifacts": {},
        "complete_artifact_ledger_sha256": "0" * 64,
        "attestation": {},
    }


