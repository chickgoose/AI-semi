class FilesystemAndSchemaTest(unittest.TestCase):
    def test_complete_artifact_roles_include_connectivity_diagnostic(self) -> None:
        contract, _ = contract_and_sources()
        roles = contract["artifact_policy"]["fixed_roles"]
        self.assertEqual(len(roles), 19)
