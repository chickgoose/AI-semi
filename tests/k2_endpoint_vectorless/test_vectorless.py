def power_report(top: str, *, activity: str = "N.A.", user: str = "N.A.",
                 sequential: str = "0.200000", primary: str = "0.200000") -> bytes:
    return f"""Generated by:           Genus(TM) Synthesis Solution
Instance: /{top}
* User-Defined Activity : {user}
* Activity File: {activity}
* Sequential Element Activity: {sequential}
* Primary Input Activity: {primary}
Power Unit: W
    Category         Leakage     Internal    Switching        Total
    Subtotal     1.00000e-09  1.00000e-06  1.00000e-06  2.00100e-06
""".encode()


def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(vectorless.canonical(value))


def indexed_manifest(evidence_root: Path, rows: list[dict] | None = None) -> Path:
    contract = vectorless.expected_contract()
    registry = vectorless.validate_contract(ROOT, contract)
    document = {
        "schema": "k2_endpoint_vectorless_evidence_v2",
        "evidence_class": contract["evidence_class"],
        "candidate_order": contract["candidate_order"],
        "comparability_policy": contract["comparability_policy"],
        "bindings": vectorless.contract_identity(ROOT, contract, registry),
        "rows": rows if rows is not None else [],
    }
    path = evidence_root / "vectorless-evidence.json"
    write_json(path, document)
    return path


class VectorlessContractTest(unittest.TestCase):
    def test_contract_reuses_native_runner_and_exact_three_endpoints(self) -> None:
        contract = vectorless.expected_contract()
        registry = vectorless.validate_contract(ROOT, contract)
        self.assertEqual(contract["schema"], "k2_endpoint_vectorless_contract_v2")
        self.assertEqual(registry["goal_order"], ["fovea_a7", "a2_p6", "a3_p6"])
        self.assertEqual(registry["selected_timing_cohort"]["period_ns"], 6.5)
        self.assertEqual(contract["genus_default_vectorless"], {
            "primary_input_activity": 0.2,
            "sequential_element_activity": 0.2,
        })
        self.assertEqual(contract["reuse"]["genus_runner"]["path"],
                         "physical/k2_w2_genus/run_genus.py")

    def test_driver_is_exact_native_default_vectorless_driver(self) -> None:
        contract = vectorless.expected_contract()
        base = (ROOT / contract["reuse"]["base_driver"]["path"]).read_bytes()
        actual = vectorless.default_vectorless_driver(ROOT, contract)
        self.assertEqual(actual, base)
        lowered = actual.lower()
        self.assertNotIn(b"read_vcd", lowered)
        self.assertNotIn(b"read_saif", lowered)
        self.assertNotIn(b"set_switching_activity", lowered)
        self.assertEqual(actual.count(b"report_power  >"), 1)

    def test_mutated_default_or_comparability_contract_rejects(self) -> None:
        mutations = []
        period = copy.deepcopy(vectorless.expected_contract())
        period["period_ns"] = 5.7
        mutations.append(period)
        default = copy.deepcopy(vectorless.expected_contract())
        default["genus_default_vectorless"]["primary_input_activity"] = 0.1
        mutations.append(default)
        roster = copy.deepcopy(vectorless.expected_contract())
        roster["candidate_order"] = ["a2_p6", "a3_p6"]
        mutations.append(roster)
        for mutated in mutations:
            with self.subTest(mutated=mutated), self.assertRaises(
                    vectorless.VectorlessError):
                vectorless.validate_contract(ROOT, mutated)

    def test_preflight_is_cadence_free_honest_hold(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "preflight.json"
            result = subprocess.run(
                ["python3", str(FLOW), "preflight", "--repo-root", str(ROOT),
                 "--output", str(output)], text=True, capture_output=True,
                check=False)
            self.assertEqual(result.returncode, 0, result.stderr)
            receipt = json.loads(output.read_text())
            self.assertEqual(receipt["status"], "HOLD_NO_REAL_SERVER_ARTIFACTS")
            self.assertFalse(receipt["comparison_ready"])
            self.assertFalse(receipt["candidate_go"])
            self.assertFalse(receipt["activity_annotated"])
            self.assertEqual(receipt["power_method"], "GENUS_DEFAULT_VECTORLESS")
            self.assertIn("Cadence was not invoked", receipt["reason"])

    def test_preflight_never_calls_native_runner(self) -> None:
        with tempfile.TemporaryDirectory() as temporary, mock.patch.object(
                vectorless.run_genus, "run_flow",
                side_effect=AssertionError("preflight invoked EDA")) as runner:
            vectorless.preflight(ROOT, Path(temporary) / "preflight.json")
            runner.assert_not_called()

    def test_execute_does_not_replace_or_patch_runner_driver(self) -> None:
        source = FLOW.read_text()
        self.assertNotIn("run_genus.DRIVER_TCL =", source)
        self.assertNotIn("TemporaryDirectory", source)
        self.assertIn("run_genus.run_flow(", source)

    def test_execute_rejects_existing_root_before_runner_call(self) -> None:
        with tempfile.TemporaryDirectory() as temporary, mock.patch.object(
                vectorless.run_genus, "run_flow",
                side_effect=AssertionError("runner should not be called")) as runner:
            args = argparse.Namespace(
                attempt_prefix="test", output_root=Path(temporary))
            with self.assertRaises(FileExistsError):
                vectorless.execute(args)
            runner.assert_not_called()

    def test_provider_hashes_are_current(self) -> None:
        contract = vectorless.expected_contract()
        for row in contract["reuse"].values():
            payload = (ROOT / row["path"]).read_bytes()
            self.assertEqual(hashlib.sha256(payload).hexdigest(), row["sha256"])


class PowerReportTest(unittest.TestCase):
    TOP = "w2_a2_p6_physical_staging_top"
    DEFAULTS = {"primary_input_activity": 0.2,
                "sequential_element_activity": 0.2}

    def test_requires_and_parses_exact_native_default_headers(self) -> None:
        result = vectorless.parse_power_report(
            power_report(self.TOP), self.TOP, self.DEFAULTS)
        self.assertAlmostEqual(result["total_mw"], 0.002001)
        self.assertAlmostEqual(result["leakage_mw"], 0.000001)

    def test_missing_activity_headers_mutation_rejects(self) -> None:
        payload = power_report(self.TOP).replace(b"* Activity File: N.A.\n", b"")
        with self.assertRaisesRegex(vectorless.VectorlessError,
                                    "exactly one Activity File"):
            vectorless.parse_power_report(payload, self.TOP, self.DEFAULTS)

    def test_nonexact_or_imported_activity_mutations_reject(self) -> None:
        reports = (
            power_report(self.TOP, activity="N/A"),
            power_report(self.TOP, activity="waves/run.vcd"),
            power_report(self.TOP, user="Imported"),
            power_report(self.TOP, sequential="0.1"),
            power_report(self.TOP, primary="0.3"),
        )
        for report in reports:
            with self.subTest(report=report), self.assertRaises(
                    vectorless.VectorlessError):
                vectorless.parse_power_report(report, self.TOP, self.DEFAULTS)

    def test_wrong_top_units_and_bad_sum_reject(self) -> None:
        valid = power_report(self.TOP)
        mutations = (
            valid.replace(self.TOP.encode(), b"wrong_top"),
            valid.replace(b"Power Unit: W", b"Power Unit: mW"),
            valid.replace(b"2.00100e-06", b"9.00000e-06"),
        )
        for report in mutations:
            with self.subTest(report=report), self.assertRaises(
                    vectorless.VectorlessError):
                vectorless.parse_power_report(report, self.TOP, self.DEFAULTS)


class ProducerEvidenceMutationTest(unittest.TestCase):
    TOP = "w2_a2_p6_physical_staging_top"

    def valid_log(self) -> bytes:
        return (f"Version: 23.14-s090_1\nW2_GENUS_PASS top={self.TOP}\n"
                "Info=12, Warn=3, Error=0, Fatal=0\nNormal exit.\n").encode()

    def test_fake_log_mutations_are_not_proof(self) -> None:
        valid = self.valid_log()
        vectorless.verify_genus_log(valid, self.TOP, "23.14-s090_1")
        mutations = (
            valid.replace(b"Normal exit.\n", b""),
            valid.replace(b"Error=0", b"Error=1"),
            valid.replace(b"W2_GENUS_PASS", b"CALLER_SAYS_PASS"),
            valid + b"set_switching_activity -toggle_rate 0.2 [get_db ports]\n",
        )
        for payload in mutations:
            with self.subTest(payload=payload), self.assertRaises(
                    vectorless.VectorlessError):
                vectorless.verify_genus_log(payload, self.TOP, "23.14-s090_1")

    def test_fake_mapped_netlist_hash_mutation_rejects(self) -> None:
        netlist = b"module mapped(); endmodule\n"
        digest = hashlib.sha256(netlist).hexdigest()
        self.assertEqual(vectorless.verify_bound_bytes(
            netlist, digest, "mapped netlist"), digest)
        with self.assertRaisesRegex(vectorless.VectorlessError, "bytes/hash mismatch"):
            vectorless.verify_bound_bytes(
                netlist + b"// caller mutation\n", digest, "mapped netlist")
        with self.assertRaisesRegex(vectorless.VectorlessError, "malformed"):
            vectorless.verify_bound_bytes(netlist, "caller-says-pass", "mapped netlist")

