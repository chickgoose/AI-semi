class EvidenceIndexTest(unittest.TestCase):
    def test_index_contains_only_canonical_attempt_locators(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            contract = vectorless.expected_contract()
            registry = vectorless.validate_contract(ROOT, contract)
            attempts = []
            for key in contract["candidate_order"]:
                attempt = root / key
                attempt.mkdir()
                attempts.append((key, attempt))
            evidence = vectorless.build_evidence(root, contract, registry, attempts)
            self.assertNotIn("execution_class", evidence)
            for row in evidence["rows"]:
                self.assertEqual(set(row), {"design", "top", "attempt_directory"})
                self.assertNotIn("sha256", row)


